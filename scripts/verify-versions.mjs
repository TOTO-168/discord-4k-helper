import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const plist = await readFile("Info.plist", "utf8");
const project = await readFile("Windows/Discord4KHelper.Windows/Discord4KHelper.Windows.csproj", "utf8");
const version = plist.match(/<key>CFBundleShortVersionString<\/key>\s*<string>([^<]+)<\/string>/)?.[1];
assert.match(version ?? "", /^\d+\.\d+\.\d+$/);
assert.equal(project.match(/<Version>([^<]+)<\/Version>/)?.[1], version);
assert.equal(project.match(/<FileVersion>([^<]+)<\/FileVersion>/)?.[1], version + ".0");
if (process.env.GITHUB_REF?.startsWith("refs/tags/")) assert.equal(process.env.GITHUB_REF, "refs/tags/v" + version);
console.log("Mac, Windows and release tag versions agree: " + version);
